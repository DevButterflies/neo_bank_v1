"""Candidate persistence service (SQLAlchemy over the shared orchestrator DB).

CRUD + lifecycle-field updates for :class:`~bank.pillars.p1.models.Candidate`.
Uses the governance ``async_session_factory`` so candidate rows live in the
same ``data/orchestrator.db`` as the P3/P4 KvStore and governance registries.

Payment behaviour and simulation state are stored as JSON on the row and
hydrated back into typed objects at use time.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any

from sqlalchemy import delete, func, or_, select, update

from bank.orchestrator.governance.database import async_session_factory

from bank.pillars.p1.behavior_gen import generate_behavior
from bank.pillars.p1.models import Candidate
from bank.pillars.p1.schemas import CandidateCreate, CandidateImport, PaymentBehavior


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


class CandidateNotFoundError(Exception):
    pass


class CandidateStateError(Exception):
    pass


class CandidateDuplicateError(Exception):
    """Raised when an import re-creates a candidate that already exists.

    Duplicate detection keys on ``national_id`` (when supplied) or the
    case-insensitive full display name — the two identifiers the demo uses to
    recognise "the same borrower" across imports.
    """

    pass


class CandidateService:
    """Thin async CRUD facade over the ``p1_candidates`` table."""

    def __init__(self) -> None:
        self._session_factory = async_session_factory

    # -- read -----------------------------------------------------------

    async def list(self, *, status: str | None = None) -> list[Candidate]:
        stmt = select(Candidate).order_by(Candidate.created_at.desc())
        if status:
            stmt = stmt.where(Candidate.status == status)
        async with self._session_factory() as db:
            result = await db.execute(stmt)
            return list(result.scalars().all())

    async def get(self, candidate_id: str) -> Candidate:
        async with self._session_factory() as db:
            row = await db.get(Candidate, candidate_id)
        if row is None:
            raise CandidateNotFoundError(f"Unknown candidate {candidate_id}")
        return row

    async def get_behavior(self, candidate_id: str) -> PaymentBehavior:
        cand = await self.get(candidate_id)
        return self.hydrate_behavior(cand)

    @staticmethod
    def hydrate_behavior(cand: Candidate) -> PaymentBehavior:
        raw = cand.payment_behavior
        if not raw:
            raise CandidateStateError(
                f"Candidate {cand.id} has no payment behaviour on file"
            )
        if isinstance(raw, str):
            raw = json.loads(raw)
        return PaymentBehavior.model_validate(raw)

    # -- write ----------------------------------------------------------

    async def create(self, payload: CandidateCreate, *, seed_profile: str | None = None) -> Candidate:
        candidate_id = None  # assigned by the model default on flush

        # Build the static row; id is generated by the ORM default, so create
        # the candidate first, then attach the id-derived behaviour.
        cand = Candidate(
            seed_profile=seed_profile,
            first_name=payload.first_name,
            last_name=payload.last_name,
            name_ar=payload.name_ar,
            gender=payload.gender,
            age=payload.age,
            national_id=payload.national_id,
            phone=payload.phone,
            city=payload.city,
            employer_name=payload.employer_name,
            employer_type=payload.employer_type,
            employment_years=payload.employment_years,
            employer_start_date=payload.employer_start_date,
            job_title=payload.job_title,
            monthly_salary=payload.monthly_salary,
            product=payload.product,
            requested_amount=payload.requested_amount,
            requested_tenure_months=payload.requested_tenure_months,
            payment_behavior={},
            sim_state={"current_month": 0, "payments_made": []},
        )
        async with self._session_factory() as db:
            db.add(cand)
            await db.flush()  # assigns cand.id
            candidate_id = cand.id
            if payload.payment_behavior is not None:
                behavior = payload.payment_behavior
            else:
                behavior = generate_behavior(
                    candidate_id,
                    requested_amount=payload.requested_amount,
                    requested_tenure_months=payload.requested_tenure_months,
                    outcome=payload.outcome_override,
                )
            cand.payment_behavior = behavior.model_dump()
            await db.commit()
        return cand

    async def update_status(
        self, candidate_id: str, status: str, **extra: Any
    ) -> Candidate:
        async with self._session_factory() as db:
            cand = await db.get(Candidate, candidate_id)
            if cand is None:
                raise CandidateNotFoundError(f"Unknown candidate {candidate_id}")
            cand.status = status
            for key, value in extra.items():
                if hasattr(cand, key):
                    setattr(cand, key, value)
            await db.commit()
        return cand

    async def set_sim_state(self, candidate_id: str, state: dict) -> None:
        async with self._session_factory() as db:
            cand = await db.get(Candidate, candidate_id)
            if cand is not None:
                cand.sim_state = state
                await db.commit()

    async def try_transition(
        self, candidate_id: str, from_status: str, to_status: str
    ) -> bool:
        """Atomically move *candidate_id* from ``from_status`` to ``to_status``.

        A conditional UPDATE keyed on the current status — SQLite has no
        ``FOR UPDATE`` row lock, so this optimistic transition is the safe way
        to prevent two concurrent callers (double-click / retry-on-timeout)
        from both observing ``approved`` and running the same state-changing
        action twice. Returns True only if exactly one row transitioned.
        """
        async with self._session_factory() as db:
            result = await db.execute(
                update(Candidate)
                .where(Candidate.id == candidate_id, Candidate.status == from_status)
                .values(status=to_status)
            )
            await db.commit()
            return result.rowcount == 1

    async def import_candidate(self, payload: CandidateImport, *, seed_profile: str | None = None) -> Candidate:
        """Import a candidate from an exported JSON (see ``export_candidates.py``).

        Stores the full ``application_json`` and ``sim_state`` as-is.  If the
        JSON carries a ``payment_behavior`` it is used verbatim; otherwise one
        is auto-generated.  Status is always set to ``new`` so the demo
        pipeline can be re-run from scratch.

        Rejects re-imports of an existing borrower (same ``national_id`` or
        same full name) with :class:`CandidateDuplicateError` so the demo can
        never build a second row for the same person.
        """
        cand = Candidate(
            seed_profile=seed_profile or payload.seed_profile,
            first_name=payload.first_name,
            last_name=payload.last_name,
            name_ar=payload.name_ar,
            gender=payload.gender,
            age=payload.age,
            national_id=payload.national_id,
            phone=payload.phone,
            city=payload.city,
            employer_name=payload.employer_name,
            employer_type=payload.employer_type,
            employment_years=payload.employment_years,
            employer_start_date=payload.employer_start_date,
            job_title=payload.job_title,
            monthly_salary=payload.monthly_salary,
            product=payload.product,
            requested_amount=payload.requested_amount,
            requested_tenure_months=payload.requested_tenure_months,
            application_json=payload.application_json,
            sim_state=payload.sim_state or {"current_month": 0, "payments_made": []},
            payment_behavior={},
            status="new",
        )
        dup_conditions = []
        if payload.national_id:
            dup_conditions.append(Candidate.national_id == payload.national_id)
        dup_conditions.append(
            func.lower(func.concat(Candidate.first_name, " ", Candidate.last_name))
            == func.lower(func.concat(payload.first_name, " ", payload.last_name))
        )
        async with self._session_factory() as db:
            existing = (
                await db.execute(
                    select(Candidate).where(or_(*dup_conditions)).limit(1)
                )
            ).scalars().first()
            if existing is not None:
                raise CandidateDuplicateError(
                    f"Candidate already exists: national_id="
                    f"{payload.national_id or '-'}, display_name="
                    f"{existing.display_name!r} (id={existing.id})"
                )
            db.add(cand)
            await db.flush()

            if payload.payment_behavior is not None:
                cand.payment_behavior = payload.payment_behavior.model_dump()
            else:
                behavior = generate_behavior(
                    cand.id,
                    requested_amount=payload.requested_amount,
                    requested_tenure_months=payload.requested_tenure_months,
                    outcome=payload.outcome_override,
                )
                cand.payment_behavior = behavior.model_dump()

            await db.commit()
        return cand

    async def delete(self, candidate_id: str) -> None:
        async with self._session_factory() as db:
            await db.execute(
                delete(Candidate).where(Candidate.id == candidate_id)
            )
            await db.commit()

    async def reset_all(self) -> int:
        async with self._session_factory() as db:
            result = await db.execute(delete(Candidate))
            await db.commit()
        return result.rowcount or 0


service = CandidateService()